#DATA TYPES: there are two types of data types
#1)MUTABLE -> can change there value [ex = list,dictionary]
#2)IMMUTABLE -> cannot change value [ex = string,tuple,set]

#type() used to find the data type of a variable or value

a = 5  #integer
print(a,type(a))  

b = 3.5 #float
print(b,type(b))

c = 1+2j #complex
print(c,type(c))

d = "aayushi" #string
print(d,type(d))

e = "32" #string
print(e,type(e))

list = [72,83,12,32]
print(list,type(list))

dict = {1 : "aayushi", 2 : "shivesh"}
print(dict,type(dict))

tuple = (2,4,3)
print(tuple,type(tuple))

set = {1,2,3,4}
print(set,type(set))








